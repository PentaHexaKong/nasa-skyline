// Splits each pipeline result into a small summary (pre-rendered) and the
// per-day Sun tracks (lazy-loaded), so first paint never waits on 600 KB.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const source = join(root, 'data')
const out = join(root, 'src', 'data', 'generated')

rmSync(out, { recursive: true, force: true })
// Vitest caches transformed modules with their import.meta.glob results inlined; stale entries would hide new data.
rmSync(join(root, 'node_modules', '.vitest-cache'), { recursive: true, force: true })
mkdirSync(out, { recursive: true })

const sites = []
for (const file of readdirSync(source)
  .filter((f) => f.endsWith('.json'))
  .sort()) {
  const result = JSON.parse(readFileSync(join(source, file), 'utf8'))
  const id = result.site.id
  const { days, ...rest } = result
  const summary = {
    ...rest,
    days: days.map(({ track, earth_track, ...day }) => day),
  }
  // Moon sites also carry Earth's hourly path; it rides along with the lazy Sun tracks.
  const tracks = Object.fromEntries(days.map((d) => [d.date, d.earth_track ? { ...d.track, earth: d.earth_track } : d.track]))
  writeFileSync(join(out, `${id}.summary.json`), JSON.stringify(summary))
  writeFileSync(join(out, `${id}.tracks.json`), JSON.stringify(tracks))
  sites.push({
    id,
    name: result.site.name,
    body: result.site.body ?? 'moon',
    observerHeightM: result.site.observer_height_m,
    referenceStartUtc: result.params.start,
    hasTerrain: existsSync(join(source, 'terrain', `${id}.json`)),
  })
}
writeFileSync(join(out, 'sites.json'), JSON.stringify(sites))
// Local terrain for the 3D island: a small heightmap (.bin) and its metadata per site.
for (const dir of ['terrain', 'moon', 'feeds'])
  if (existsSync(join(source, dir))) cpSync(join(source, dir), join(out, dir), { recursive: true })
function jsonFeedPaths(directory, prefix = '') {
  const paths = []
  for (const entry of readdirSync(directory, { withFileTypes: true }).sort((left, right) => left.name.localeCompare(right.name))) {
    const relativePath = `${prefix}${entry.name}`
    if (entry.isDirectory()) paths.push(...jsonFeedPaths(join(directory, entry.name), `${relativePath}/`))
    else if (entry.isFile() && entry.name.endsWith('.json')) paths.push(relativePath)
  }
  return paths
}

function moduleString(value) {
  const jsonValue = JSON.stringify(value)
  return "'" + jsonValue.slice(1, -1).replaceAll("'", "\\'") + "'"
}

const feedFiles = existsSync(join(out, 'feeds')) ? jsonFeedPaths(join(out, 'feeds')) : []
const feedImports = feedFiles.map((path) => `  ${moduleString(path)}: () => import(${moduleString(`./feeds/${path}`)}),`)
writeFileSync(
  join(out, 'feedIndex.ts'),
  `// Generated by sync-data.mjs. Explicit imports track scenario additions and removals.\nexport const deliveredFeeds: Record<string, () => Promise<{ default: unknown }>> = {\n${feedImports.join('\n')}\n}\n`,
)

console.log(`sync-data: ${sites.map((s) => s.id).join(', ')} -> src/data/generated`)
