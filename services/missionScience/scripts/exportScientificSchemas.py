import argparse
import json
from pathlib import Path

from pydantic import TypeAdapter
from skyline_mission_science.mastFeeds import MastFeedV1, MastManifest
from skyline_mission_science.mastPlacementModels import MastPlacementRequest, MastPlacementResponse
from skyline_mission_science.mastPowerModels import MastPowerRequest, MastPowerResponse
from skyline_mission_science.scientificModels import (
    ScientificRequest,
    ScientificResponse,
)


def typeScriptType(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        return (
            repr(schema['const'])
            if isinstance(schema['const'], str)
            else json.dumps(schema['const'])
        )
    if 'enum' in schema:
        return ' | '.join(repr(value) for value in schema['enum'])
    alternatives = schema.get('anyOf', schema.get('oneOf'))
    if alternatives:
        return ' | '.join(typeScriptType(value) for value in alternatives)
    kind = schema.get('type')
    if kind == 'array':
        return 'Array<' + typeScriptType(schema.get('items', {})) + '>'
    if kind == 'object':
        if not schema.get('properties'):
            extra = schema.get('additionalProperties', True)
            return (
                'Record<string, '
                + (typeScriptType(extra) if isinstance(extra, dict) else 'unknown')
                + '>'
            )
        required = schema.get('required', [])
        fields = [
            key + ('' if key in required else '?') + ': ' + typeScriptType(value)
            for key, value in schema['properties'].items()
        ]
        return '{\n  ' + '\n  '.join(fields) + '\n}'
    return {
        'string': 'string',
        'number': 'number',
        'integer': 'number',
        'boolean': 'boolean',
        'null': 'null',
    }.get(kind, 'unknown')


def withoutDefaults(value):
    if isinstance(value, dict):
        return {
            key: withoutDefaults(item)
            for key, item in value.items()
            if key != 'default'
        }
    if isinstance(value, list):
        return [withoutDefaults(item) for item in value]
    return value


def exportSchemas(appRoot):
    definitions = {}
    declarations = []
    contracts = appRoot / 'contracts'
    frontend = appRoot / 'frontend/src/lib'
    contracts.mkdir(parents=True, exist_ok=True)
    for name, adapter, mode in [
        ('ScientificRequest', TypeAdapter(ScientificRequest), 'validation'),
        ('ScientificResponse', TypeAdapter(ScientificResponse), 'serialization'),
        ('MastPowerRequest', TypeAdapter(MastPowerRequest), 'validation'),
        ('MastPowerResponse', TypeAdapter(MastPowerResponse), 'serialization'),
        ('MastPlacementRequest', TypeAdapter(MastPlacementRequest), 'validation'),
        ('MastPlacementResponse', TypeAdapter(MastPlacementResponse), 'serialization'),
        ('MastFeedV1', TypeAdapter(MastFeedV1), 'serialization'),
        ('MastManifest', TypeAdapter(MastManifest), 'serialization'),
    ]:
        schema = adapter.json_schema(mode=mode)
        if mode == 'serialization':
            schema = withoutDefaults(schema)
        schema['$schema'] = 'https://json-schema.org/draft/2020-12/schema'
        filename = name[0].lower() + name[1:] + '.schema.json'
        encoded = json.dumps(schema, indent=2) + '\n'
        for target in [contracts / filename, frontend / filename]:
            target.write_text(encoded, encoding='utf-8')
        definitions.update(schema.get('$defs', {}))
        declarations.append('export type ' + name + ' = ' + typeScriptType(schema))
    for name, schema in definitions.items():
        if name not in {
            'ScientificRequest',
            'ScientificResponse',
            'MastPowerRequest',
            'MastPowerResponse',
            'MastPlacementRequest',
            'MastPlacementResponse',
            'MastFeedV1',
            'MastManifest',
        }:
            declarations.append('export type ' + name + ' = ' + typeScriptType(schema))
    (frontend / 'scientificContract.generated.ts').write_text(
        '// Generated by scripts/exportScientificSchemas.py from authoritative Pydantic models.\n\n'
        + '\n\n'.join(declarations)
        + '\n',
        encoding='utf-8',
    )


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--app-root', type=Path, default=Path(__file__).resolve().parents[3])
    exportSchemas(parser.parse_args().app_root)
